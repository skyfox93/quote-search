class EpisodeText < ApplicationRecord
  has_many :episode_chunks, dependent: :delete_all

  SERIES = {
    "TOS" => "Star Trek: The Original Series",
    "TAS" => "Star Trek: The Animated Series",
    "TNG" => "Star Trek: The Next Generation",
    "DS9" => "Star Trek: Deep Space Nine",
    "VOY" => "Star Trek: Voyager",
    "ENT" => "Star Trek: Enterprise"
  }.freeze

  # Pulls the episode title out of a raw transcript header, which looks like
  #   "The Next Generation Transcripts - The Best of Both\nWorlds, Part One\n\n\n\nThe\nBest of Both Worlds, Part One\nStardate: ..."
  # The first line can wrap mid-title, so prefer the full title block that sits
  # just above "Stardate:" / "Original Airdate:", and fall back to the first line.
  def self.title_from_script(raw)
    header = raw.to_s.split(/Stardate:|Original Airdate:/).first.to_s
    block = header.split(/\r?\n[ \t\r]*\r?\n/).map(&:squish).reject(&:empty?).last
    block = block&.sub(/\s*Mission date:.*\z/i, "") # Enterprise headers
    block = nil if block.blank? || block =~ /Transcripts|copyright/i
    title = block || header[/Transcripts?\s*-\s*([^\r\n]+)/, 1]
    title&.squish.presence
  end

  # e.g. { ["TNG", "episode 0"] => "Season 1, Ep 1: Encounter at Farpoint" }
  def self.titles_for(records)
    pairs = records.map { |r| [r.series, r.episode] }.uniq
    return {} if pairs.empty?

    conditions = pairs.map { "(series = ? AND episode = ?)" }.join(" OR ")
    where(conditions, *pairs.flatten).pluck(:series, :episode, :season, :episode_number, :title)
      .to_h do |series, episode, season, number, title|
        [[series, episode], label(season: season, episode_number: number, title: title, fallback: episode)]
      end
  end

  # Everything except the (large) transcript, for lists of episodes.
  LIST_COLUMNS = %i[id series episode season episode_number title summary].freeze
  scope :without_text, -> { select(*LIST_COLUMNS) }

  # Lowercase, US spelling, no punctuation or leading "the", and every
  # "Part One" / "Part II" / "(1)" written as "part 1", so titles from
  # different sources (transcripts, TVMaze, an LLM) compare equal.
  def self.normalize_title(name)
    t = name.to_s.unicode_normalize(:nfkd).downcase.delete("'’")
    t = t.gsub(/our\b/) { |m| %w[honour favour].any? { t.include?(_1) } ? "or" : m }
    t = t.gsub(/\((\d)\)/, ' part \1')
         .gsub(/\bpart\s+(one|i)\b/, "part 1").gsub(/\bpart\s+(two|ii)\b/, "part 2")
         .gsub(/\b(ii)\s*\z/, "part 2").gsub(/\bi\s*\z/, "part 1")
    t = t.gsub(/[^a-z0-9 ]/, " ").squeeze(" ").strip.delete_prefix("the ")
    t.gsub(/\s+part 1\z/, "") # "X" and "X, Part One" name the same episode
  end

  NUMBERS_FILE = Rails.root.join("db/episode_numbers.json")

  # Season/episode numbers per transcript, generated by `bin/rails episodes:fetch_numbers`.
  # e.g. numbers["TNG"]["episode 0"] => { "season" => 1, "number" => 1 }
  def self.numbers
    @numbers ||= NUMBERS_FILE.exist? ? JSON.parse(NUMBERS_FILE.read) : {}
  end

  # "Season 1, Ep 1: Encounter at Farpoint"
  def self.label(season:, episode_number:, title:, fallback:)
    name = title.presence || fallback
    if season && episode_number
      "Season #{season}, Ep #{episode_number}: #{name}"
    elsif season
      "Season #{season}, Pilot: #{name}"
    else
      name
    end
  end

  def display_title
    title.presence || "#{series} #{episode}"
  end

  def full_title
    self.class.label(season: season, episode_number: episode_number, title: title, fallback: "#{series} #{episode}")
  end

  def series_name
    SERIES[series] || series
  end

  # "S4 · E24", "S1 · Pilot", or nil
  def short_number
    return unless season

    episode_number ? "S#{season} · E#{episode_number}" : "S#{season} · Pilot"
  end

  # Stardate and airdate from the transcript header, when present.
  def stardate = header_field("Stardate")
  def airdate = header_field("Original Airdate")

  private

  def header_field(name)
    text.to_s[0, 600][/#{name}:\s*(.+?)(?=\s{2,}|\s+(?:Stardate|Original Airdate):|\n|\z)/, 1]&.strip.presence
  end
end
